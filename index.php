        <div class="tab-panel" role="tabpanel" id="panel-warm" aria-labelledby="tab-warm" hidden>
          <div class="panel-copy">
            <p class="panel-kicker">Bermuda · zoysia · St. Augustine</p>
            <h3>It means to look dead.</h3>
            <p>Warm-season grasses go fully dormant after the first hard frost and turn tan to straw. That colour is not a diagnosis. The crowns are alive below the soil, waiting for reliable warmth, and most winter damage comes from doing too much rather than too little.</p>
            <ul class="ticks">
              <li>No nitrogen after late summer; it fuels growth that cannot harden.</li>
              <li>Do not rake, aerate, or dethatch while fully dormant.</li>
              <li>Delay spring cleanup until green-up actually starts.</li>
              <li>In cold-snap regions, extra thatch is insulation — leave a little.</li>
            </ul>
