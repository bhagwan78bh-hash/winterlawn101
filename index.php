      <div class="tab-panels">
        <div class="tab-panel" role="tabpanel" id="panel-cool" aria-labelledby="tab-cool">
          <div class="panel-copy">
            <p class="panel-kicker">Fescue · bluegrass · rye</p>
            <h3>It stays half awake.</h3>
            <p>Cool-season grasses keep photosynthesising whenever soil is above roughly 5°C, which means winter is a slow season, not a dead one. They hold colour longer, tolerate frost better, and reward a late-autumn tidy-up.</p>
            <ul class="ticks">
              <li>Cut to 5–6 cm for the final mow; raise the deck in spring.</li>
              <li>Clear leaves so crowns can breathe through wet weeks.</li>
              <li>Dormant seeding works in late winter, when freeze–thaw works seed into the soil.</li>
              <li>Avoid heavy traffic on frost; repair bare spots in early autumn, not December.</li>
            </ul>
          </div>
