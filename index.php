        <p class="eyebrow reveal">04 <span class="eyebrow-rule"></span> Know your grass</p>
        <h2 class="reveal" style="--d:1">Two lawns,<br>two winters.</h2>
        <p class="section-lede reveal" style="--d:2">The biggest mistake in winter care is applying cool-season advice to a warm-season lawn. Pick the one that looks like yours.</p>
      </div>

      <div class="tabs" role="tablist" aria-label="Grass type">
        <button class="tab is-active" role="tab" aria-selected="true" aria-controls="panel-cool" id="tab-cool" tabindex="0">Cool-season</button>
