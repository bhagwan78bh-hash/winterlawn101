  <section class="section faq" id="faq">
    <div class="wrap faq-grid">
      <div class="faq-intro">
        <p class="eyebrow reveal">06 <span class="eyebrow-rule"></span> Questions</p>
        <h2 class="reveal" style="--d:1">The things<br>you're wondering.</h2>
        <p class="reveal" style="--d:2">Short answers, no hedging. If your situation is unusual — coastal, high altitude, new build — a local extension office beats any guide.</p>
      </div>

      <div class="faq-list">
        <details class="reveal" open>
          <summary>When should I stop mowing?</summary>
          <p>When top growth has effectively stopped, usually as soil at 5 cm drops below about 5°C (41°F). Make the final cut 5–6 cm, and never remove more than a third of the blade in one pass.</p>
        </details>
        <details class="reveal">
          <summary>Should I fertilize in winter?</summary>
          <p>No. Nitrogen this late fuels tender growth that winter-kills. A potassium-forward feed belongs in early to mid-autumn, and nothing should go down on frozen ground.</p>
        </details>
        <details class="reveal">
          <summary>Can I water in winter?</summary>
          <p>Only in dry, unfrozen spells. One deep soak of about 2 cm every two to three weeks is better than frequent light watering. Never irrigate frozen soil — it runs off and refreezes.</p>
        </details>
        <details class="reveal">
          <summary>Does walking on frost really damage grass?</summary>
          <p>Yes. Frozen blades snap instead of bending, which can fracture the crown beneath. Keep foot traffic off frosted turf until it thaws, and vary the dog's route.</p>
        </details>
        <details class="reveal">
          <summary>Will snow kill my lawn?</summary>
          <p>Snow itself insulates and rarely kills grass. Prolonged wet cover can encourage snow mold, and ice or heavy piled snow can smother turf. Shovel onto paths and beds, not the lawn.</p>
        </details>
        <details class="reveal">
          <summary>When is the best time to overseed?</summary>
          <p>Early autumn for cool-season grasses. Dormant seeding in late winter is a solid second option. For warm-season grasses, wait until late spring or early summer, when soil is reliably warm.</p>
        </details>
      </div>
    </div>
