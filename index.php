  <section class="section protocol" id="protocol">
    <div class="wrap">
      <div class="section-head">
        <p class="eyebrow reveal">01 <span class="eyebrow-rule"></span> The protocol</p>
        <h2 class="reveal" style="--d:1">Five moves<br>before the frost.</h2>
        <p class="section-lede reveal" style="--d:2">Nothing here is exotic. It is the difference between a lawn that coasts into dormancy and one that spends March recovering from December.</p>
      </div>

      <ol class="steps">
        <li class="step reveal">
          <span class="step-num">01</span>
          <div class="step-body">
            <h3>Drop the deck, don't scalp.</h3>
            <p>Take the last cut down to 5–6 cm over two passes, never more than a third of the blade at a time. Long grass mats under snow and invites snow mold; scalped grass exposes the crown to ice.</p>
          </div>
          <span class="step-when">Late Oct<br>first frost</span>
        </li>
        <li class="step reveal">
          <span class="step-num">02</span>
          <div class="step-body">
            <h3>Feed potassium, skip nitrogen.</h3>
            <p>A potassium-forward feed hardens cell walls before winter. Nitrogen this late pushes tender growth that winter-kills. If you missed the window, skip it — spring is soon enough.</p>
          </div>
          <span class="step-when">Early–mid<br>autumn</span>
        </li>
        <li class="step reveal">
          <span class="step-num">03</span>
          <div class="step-body">
            <h3>Clear the blanket.</h3>
            <p>Leaves and thatch hold moisture against the soil and smother crowns. Rake, mulch with the mower, or compost. A lawn that can breathe in December is a lawn that drains in March.</p>
          </div>
          <span class="step-when">Through<br>leaf fall</span>
        </li>
        <li class="step reveal">
          <span class="step-num">04</span>
          <div class="step-body">
            <h3>Water deep, and rarely.</h3>
            <p>No rain for three weeks and the ground still open? One deep soak of about 2 cm beats weekly sprinkling. Never irrigate frozen ground — it sheets off and refreezes.</p>
          </div>
          <span class="step-when">Dry,<br>unfrozen spells</span>
        </li>
        <li class="step reveal">
          <span class="step-num">05</span>
          <div class="step-body">
            <h3>Stay off the frost.</h3>
            <p>Frozen blades snap instead of bending, fracturing the crown beneath. Wait for the thaw before walking, mowing, or letting the dog out on the same path twice.</p>
          </div>
          <span class="step-when">Every<br>frosty morning</span>
        </li>
      </ol>
    </div>
