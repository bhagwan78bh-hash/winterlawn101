        <p class="eyebrow reveal">05 <span class="eyebrow-rule"></span> Winter myths</p>
        <h2 class="reveal" style="--d:1">Four things<br>people get wrong.</h2>
      </div>

      <div class="myth-grid">
        <article class="myth reveal">
          <span class="myth-tag">Myth</span>
          <h3>“Cut it short so it doesn't mat.”</h3>
          <p><strong>Actually —</strong> scalping exposes the crown to ice and leaves no insulation. Take it to 5–6 cm and stop there.</p>
        </article>
        <article class="myth reveal" style="--d:1">
          <span class="myth-tag">Myth</span>
          <h3>“A late nitrogen boost helps it green up.”</h3>
          <p><strong>Actually —</strong> it pushes soft growth straight into the first freeze. Potassium in autumn; nitrogen waits for spring.</p>
        </article>
        <article class="myth reveal" style="--d:2">
          <span class="myth-tag">Myth</span>
          <h3>“Snow is the enemy.”</h3>
          <p><strong>Actually —</strong> snow insulates. Ice, piled snow, and footprints are what compact and fracture turf.</p>
        </article>
        <article class="myth reveal" style="--d:3">
          <span class="myth-tag">Myth</span>
          <h3>“Brown means dead.”</h3>
          <p><strong>Actually —</strong> dormancy is normal for warm-season grass. Check the crowns at soil level in spring before you reseed.</p>
